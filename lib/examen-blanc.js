/**
 * Entrelacement déterministe des domaines.
 *
 * Écrites par domaine pour être relues et maintenues facilement, les questions
 * seraient servies en trois blocs — 59 People, puis 74 Process, puis 47
 * Business — ce qui ne ressemble en rien à l'examen réel, où les domaines
 * alternent en permanence.
 *
 * On les répartit donc en tourniquet pondéré, avec une contrainte : les
 * questions d'une même étude de cas doivent rester CONSÉCUTIVES, sans quoi le
 * candidat relirait le scénario à chaque fois — exactement ce qu'il faut
 * apprendre à ne pas faire.
 *
 * L'ordre est déterministe : deux passages donnent la même séquence, ce qui
 * rend deux tentatives comparables.
 */
function entrelacer(brut) {
  const seaux = { people: [], process: [], business: [] };

  // On regroupe d'abord chaque étude de cas en un bloc insécable
  const blocs = [];
  let i = 0;
  while (i < brut.length) {
    const q = brut[i];
    if (q.caseId) {
      const bloc = [];
      while (i < brut.length && brut[i].caseId === q.caseId) bloc.push(brut[i++]);
      blocs.push(bloc);
    } else {
      blocs.push([q]);
      i++;
    }
  }
  for (const bloc of blocs) seaux[bloc[0].domain].push(bloc);

  // Tourniquet pondéré : on tire dans le seau dont le retard relatif est le plus grand
  const total = blocs.reduce((n, b) => n + b.length, 0);
  const cibles = {
    people: seaux.people.reduce((n, b) => n + b.length, 0) / total,
    process: seaux.process.reduce((n, b) => n + b.length, 0) / total,
    business: seaux.business.reduce((n, b) => n + b.length, 0) / total,
  };
  const servis = { people: 0, process: 0, business: 0 };
  const sortie = [];

  while (sortie.length < total) {
    let choisi = null;
    let pireEcart = -Infinity;
    for (const cle of ["people", "process", "business"]) {
      if (seaux[cle].length === 0) continue;
      const attendu = cibles[cle] * sortie.length;
      const ecart = attendu - servis[cle];
      if (ecart > pireEcart) {
        pireEcart = ecart;
        choisi = cle;
      }
    }
    const bloc = seaux[choisi].shift();
    for (const q of bloc) sortie.push(q);
    servis[choisi] += bloc.length;
  }
  return sortie;
}

/**
 * Rééquilibrage de la position des bonnes réponses.
 *
 * Écrites à la main, les questions placent naturellement la bonne réponse en
 * deuxième position — on énonce d'abord le distracteur réflexe, puis la réponse
 * attendue. Sur 180 questions cela devient exploitable : un candidat qui
 * répondrait « B » partout obtiendrait un score absurde, et l'examen blanc
 * cesserait de mesurer quoi que ce soit.
 *
 * On fait donc tourner les options de chaque question pour que la bonne réponse
 * atterrisse sur une position cible attribuée en tourniquet. La rotation
 * préserve l'ordre relatif des options et s'applique identiquement à l'anglais
 * et au français. Le résultat est déterministe : 45 bonnes réponses par
 * position, et la même séquence à chaque exécution.
 */
function reequilibrer(questions) {
  return questions.map((q, i) => {
    const cible = i % 4;
    const decalage = (cible - q.answer + 4) % 4;
    if (decalage === 0) return q;

    const tourner = (options) => {
      const sortie = new Array(4);
      options.forEach((opt, j) => {
        sortie[(j + decalage) % 4] = opt;
      });
      return sortie;
    };

    return {
      ...q,
      en: { ...q.en, options: tourner(q.en.options) },
      fr: { ...q.fr, options: tourner(q.fr.options) },
      answer: cible,
    };
  });
}

export const QUESTIONS = reequilibrer(entrelacer(BRUT));

/** Répartition réelle par domaine, calculée sur les questions notées. */
export function repartitionReelle() {
  const notees = QUESTIONS.filter((q) => q.scored !== false);
  const r = {};
  for (const cle of ["people", "process", "business"]) {
    const n = notees.filter((q) => q.domain === cle).length;
    r[cle] = { n, pct: Math.round((n / notees.length) * 100) };
  }
  return r;
}

/**
 * Répartition par approche, pour vérifier la cible ECO de 60 % agile-hybride.
 *
 * Le pourcentage se calcule sur les questions qui portent RÉELLEMENT un
 * contexte d'approche. Une question sur la formule PERT, la distinction EEF/OPA
 * ou le calcul d'un CPI n'est ni agile ni prédictive : elle est neutre, et
 * l'inclure au dénominateur fausserait la mesure dans un sens comme dans
 * l'autre.
 */
export function repartitionApproches() {
  const r = { agile: 0, hybrid: 0, predictive: 0, neutral: 0 };
  for (const q of QUESTIONS) r[q.approach] = (r[q.approach] || 0) + 1;
  const contextuelles = r.agile + r.hybrid + r.predictive;
  return {
    ...r,
    contextuelles,
    pctAgileHybride: Math.round(((r.agile + r.hybrid) / contextuelles) * 100),
  };
}

/** Distribution des positions de bonne réponse — doit être équilibrée. */
export function distributionReponses() {
  const d = [0, 0, 0, 0];
  for (const q of QUESTIONS) d[q.answer]++;
  return { A: d[0], B: d[1], C: d[2], D: d[3] };
}
